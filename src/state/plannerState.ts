/**
 * Everything the user has entered. This is the only state that is persisted;
 * everything else (leave years, summaries, calendar cells) is derived.
 */
export interface PlannerState {
  /** Settings that apply to everyone: leave year start, region, bridge suggestions. */
  shared: SharedSettings
  /** Never empty, in display order. */
  people: Person[]
  /** Always the id of someone in `people`. */
  activePersonId: string
  /** Employers and their closures/extra holidays, in display order. At most `MAX_COMPANIES`. */
  companies: Company[]
  /** Company whose days the calendar is editing (company-day mode), or null. Not persisted. */
  editingCompanyId: string | null
  /** Leave years forward/back from the one containing today. Not persisted. */
  yearOffset: number
}

export type PlannerAction =
  | { type: 'updateSettings'; patch: Partial<Settings> }
  | { type: 'cycleLeave'; date: string }
  | { type: 'setLeaveRange'; start: string; end: string; portion: LeavePortion | undefined }
  | { type: 'clearLeaveInRange'; start: string; end: string }
  | { type: 'addPerson'; id: string; name: string; colour?: string }
  | { type: 'removePerson'; id: string }
  | { type: 'renamePerson'; id: string; name: string }
  | { type: 'setPersonColour'; id: string; colour: string }
  | { type: 'selectPerson'; id: string }
  | { type: 'addCompany'; id: string; name: string }
  | { type: 'renameCompany'; id: string; name: string }
  | { type: 'removeCompany'; id: string }
  | { type: 'selectCompany'; id: string }
  | { type: 'stopEditingCompany' }
  | { type: 'setPersonCompany'; personId: string; companyId: string | null }
  | {
      type: 'assignCompanyDays'
      companyId: string
      dates: string[]
      name: string
      deducted: boolean
      repeatsAnnually: boolean
      /** Ids for new days are `${idPrefix}-${i}`; generated by the UI so the reducer stays pure. */
      idPrefix: string
    }
  | { type: 'removeCompanyDays'; companyId: string; dates: string[] }
  | { type: 'removeCompanyDay'; companyId: string; id: string }
  | { type: 'shiftYear'; by: number }
  | { type: 'resetYear' }
  /** Replace the whole plan, e.g. from an imported file already validated by `parsePlan`. */
  | { type: 'replacePlan'; plan: StoredContent }

