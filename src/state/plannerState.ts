export const STORAGE_KEY = 'annual-leave-planner'
const SCHEMA_VERSION = 5

/** Id given to the person created from v1/v2 data or on first visit. */
const DEFAULT_PERSON_ID = 'person-1'

/** Id given to the company created on first visit or from v1-v3 data. */
const DEFAULT_COMPANY_ID = 'company-1'

/**
 * Stored shape history:
 * - v1: `{ version, settings, leave }`
 * - v2: adds `companyDays`
 * - v3: several people. `settings` splits into `shared` and per-person settings,
 *   and `leave` moves onto each person: `{ version, shared, people, activePersonId, companyDays }`
 * - v4: company days move into `companies`, each person has a `companyId`:
 *   `{ version, shared, people, activePersonId, companies }`
 * - v5: per-person fortnightly working pattern: `workingDaysWeek2`, `fortnightStart`
 *   (same envelope as v4; missing fields default on load)
 */
interface StoredStateV5 {
  version: 5
  shared: SharedSettings
  people: Person[]
  activePersonId: string
  companies: Company[]
}

export type StoredContent = Omit<StoredStateV5, 'version'>

function defaultPerson(): Person {
  return {
    ...DEFAULT_PERSON_SETTINGS,
    id: DEFAULT_PERSON_ID,
    name: DEFAULT_PERSON_NAME,
    colour: PERSON_COLOURS[0],
    leave: {},
    companyId: null,
  }
}

export function initialState(storage: Storage | undefined = safeLocalStorage()): PlannerState {
  const stored = storage ? readStored(storage) : null
  if (stored) return { ...stored, editingCompanyId: null, yearOffset: 0 }
  return {
    shared: splitSettings(DEFAULT_SETTINGS).shared,
    people: [{ ...defaultPerson(), companyId: DEFAULT_COMPANY_ID }],
    activePersonId: DEFAULT_PERSON_ID,
    companies: [{ id: DEFAULT_COMPANY_ID, name: DEFAULT_COMPANY_NAME, days: [] }],
    editingCompanyId: null,
    yearOffset: 0,
  }
}

/**
 * True when storage already holds valid saved planner data (a returning user).
 * Call it before the first `persist`, which would otherwise make every visit look returning.
 */
export function hasSavedState(storage: Storage | undefined = safeLocalStorage()): boolean {
  return storage ? readStored(storage) !== null : false
}

/** The versioned JSON envelope that is both stored and exported: exactly what `parsePlan` reads back. */
export function serialisePlan(state: PlannerState): string {
  const payload: StoredStateV5 = {
    version: SCHEMA_VERSION,
    shared: state.shared,
    people: state.people,
    activePersonId: state.activePersonId,
    companies: state.companies,
  }
  return JSON.stringify(payload)
}

export function persist(state: PlannerState, storage: Storage | undefined = safeLocalStorage()) {
  if (!storage) return
  try {
    storage.setItem(STORAGE_KEY, serialisePlan(state))
  } catch {
    // Quota exceeded or storage disabled: the app still works for this session.
  }
}

export type ParsePlanResult =
  | { ok: true; plan: StoredContent }
  | { ok: false; reason: 'not-json' | 'not-a-plan' | 'newer-version'; message: string }

/**
 * The single validation entry point for plan JSON (storage, file import, future share links).
 * Migrates older versions and sanitises every field; entries that are individually invalid
 * are dropped rather than rejecting the whole plan.
 */
export function parsePlan(json: string): ParsePlanResult {
  let parsed: unknown
  try {
    parsed = JSON.parse(json)
  } catch {
    return { ok: false, reason: 'not-json', message: 'This file isn’t valid JSON, so it can’t be a leave plan.' }
  }
  const version = parsed && typeof parsed === 'object' ? (parsed as { version?: unknown }).version : undefined
  if (typeof version === 'number' && version > SCHEMA_VERSION) {
    return { ok: false, reason: 'newer-version', message: 'This plan was made by a newer version of the app. Update the app and try again.' }
  }
  const plan = migrateStored(parsed)
  if (!plan) return { ok: false, reason: 'not-a-plan', message: 'This file isn’t a valid leave plan.' }
  return { ok: true, plan }
}

function readStored(storage: Storage): StoredContent | null {
  try {
    const raw = storage.getItem(STORAGE_KEY)
    if (!raw) return null
    const result = parsePlan(raw)
    return result.ok ? result.plan : null
  } catch {
    return null
  }
}

/** One-line description of a plan for the import confirmation. */
export function describePlan(plan: StoredContent): string {
  const booked = plan.people.reduce(
    (n, p) => n + Object.values(p.leave).reduce((m, portion) => m + (portion === 'half' ? 0.5 : 1), 0),
    0,
  )
  const companyDays = plan.companies.reduce((n, c) => n + c.days.length, 0)
  const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`
  return `${plural(plan.people.length, 'person', 'people')} (${plan.people.map((p) => p.name).join(', ')}), ${plural(booked, 'day')} booked, ${plural(plan.companies.length, 'company', 'companies')} with ${plural(companyDays, 'company day')}`
}

/**
 * Bring any known stored version up to the current shape, validating every
 * field. Returns null for unknown versions or non-objects. Add a case here
 * whenever SCHEMA_VERSION is bumped.
 */
export function migrateStored(parsed: unknown): StoredContent | null {
  if (!parsed || typeof parsed !== 'object') return null
  const p = parsed as Record<string, unknown>
  if (p.version === 1 || p.version === 2) {
    const { shared, person } = splitSettings(
      sanitiseSettings({ ...DEFAULT_SETTINGS, ...(asObject(p.settings) as Partial<Settings>) }),
    )
    return {
      shared,
      people: [{ ...defaultPerson(), ...person, leave: sanitiseLeave(p.leave), companyId: DEFAULT_COMPANY_ID }],
      activePersonId: DEFAULT_PERSON_ID,
      // v1 had no company days, so `companyDays` is simply absent and becomes [].
      companies: [legacyCompany(p.version === 1 ? [] : p.companyDays)],
    }
  }
  if (p.version !== 3 && p.version !== 4 && p.version !== 5) return null
  const shared = splitSettings(
    sanitiseSettings({ ...DEFAULT_SETTINGS, ...(asObject(p.shared) as Partial<Settings>) }),
  ).shared
  const people = sanitisePeople(p.people)
  const activePersonId =
    typeof p.activePersonId === 'string' && people.some((x) => x.id === p.activePersonId)
      ? p.activePersonId
      : people[0].id
  if (p.version === 3) {
    // Everyone shared the single list of company days, so everyone joins the one company.
    return {
      shared,
      people: people.map((x) => ({ ...x, companyId: DEFAULT_COMPANY_ID })),
      activePersonId,
      companies: [legacyCompany(p.companyDays)],
    }
  }
  const companies = sanitiseCompanies(p.companies)
  return {
    shared,
    // `sanitisePeople` keeps companyId as read; drop any that no longer resolve.
    people: people.map((x) => ({ ...x, companyId: companies.some((c) => c.id === x.companyId) ? x.companyId : null })),
    activePersonId,
    companies,
  }
}

/** The single company that v1-v3 company days migrate into. */
function legacyCompany(days: unknown): Company {
  return { id: DEFAULT_COMPANY_ID, name: DEFAULT_COMPANY_NAME, days: sanitiseCompanyDays(days) }
}

function sanitiseCompanies(value: unknown): Company[] {
  const companies: Company[] = []
  const ids = new Set<string>()
  for (const raw of Array.isArray(value) ? value : []) {
    if (companies.length >= MAX_COMPANIES) break
    if (!raw || typeof raw !== 'object') continue
    const r = raw as Record<string, unknown>
    if (typeof r.id !== 'string' || !r.id || ids.has(r.id)) continue
    ids.add(r.id)
    companies.push({
      id: r.id,
      name: cleanCompanyName(r.name) || `Company ${companies.length + 1}`,
      days: sanitiseCompanyDays(r.days),
    })
  }
  return companies
}

const asObject = (v: unknown): object => (v && typeof v === 'object' && !Array.isArray(v) ? v : {})

function sanitisePeople(value: unknown): Person[] {
  const people: Person[] = []
  const ids = new Set<string>()
  for (const raw of Array.isArray(value) ? value : []) {
    if (!raw || typeof raw !== 'object') continue
    const r = raw as Record<string, unknown>
    if (typeof r.id !== 'string' || ids.has(r.id)) continue
    ids.add(r.id)
    const index = people.length
    const settings = sanitiseSettings({ ...DEFAULT_SETTINGS, ...DEFAULT_PERSON_SETTINGS, ...pickPersonKeys(r) })
    people.push({
      ...splitSettings(settings).person,
      id: r.id,
      name: cleanName(r.name) || (index === 0 ? DEFAULT_PERSON_NAME : `Person ${index + 1}`),
      colour: isHexColour(r.colour) ? r.colour.toLowerCase() : nextPersonColour(people.map((x) => x.colour)),
      leave: sanitiseLeave(r.leave),
      companyId: typeof r.companyId === 'string' ? r.companyId : null,
    })
  }
  return people.length ? people : [defaultPerson()]
}

function pickPersonKeys(r: Record<string, unknown>): Partial<Settings> {
  const out: Record<string, unknown> = {}
  for (const k of PERSON_SETTING_KEYS) if (k in r) out[k] = r[k]
  return out as Partial<Settings>
}

function safeLocalStorage(): Storage | undefined {
  try {
    return typeof window === 'undefined' ? undefined : window.localStorage
  } catch {
    return undefined
  }
}

