/** The effective settings for one person: shared settings plus their own. */
export function personSettings(shared: SharedSettings, person: Person): Settings {
  return { ...shared, ...pickPersonSettings(person) }
}

/** The person's own settings, derived from `PERSON_SETTING_KEYS` so it can't drift. */
function pickPersonSettings(person: PersonSettings): PersonSettings {
  const out: Record<string, unknown> = {}
  for (const k of PERSON_SETTING_KEYS) out[k] = person[k]
  return out as unknown as PersonSettings
}

/** Maximum number of companies in one planner. */
export const MAX_COMPANIES = 20

/** The company a person belongs to, or undefined for none (or a dangling id). */
export function companyOf(companies: readonly Company[], person: Pick<Person, 'companyId'>): Company | undefined {
  return person.companyId === null ? undefined : companies.find((c) => c.id === person.companyId)
}

/** Company-day lookup for a person: their company's days, or none. */
export function companyIndexFor(companies: readonly Company[], person: Pick<Person, 'companyId'>): CompanyDayIndex {
  const company = companyOf(companies, person)
  return company ? companyDayIndex(company.days) : NO_COMPANY_DAYS
}

/** The person being edited. Falls back to the first person, which only matters for malformed state. */
export function activePerson(state: Pick<PlannerState, 'people' | 'activePersonId'>): Person {
  return state.people.find((p) => p.id === state.activePersonId) ?? state.people[0]
}

const PERSON_KEY_SET: ReadonlySet<string> = new Set(PERSON_SETTING_KEYS)

function splitSettings(s: Settings): { shared: SharedSettings; person: PersonSettings } {
  const shared: Record<string, unknown> = {}
  const person: Record<string, unknown> = {}
  for (const [k, v] of Object.entries(s)) (PERSON_KEY_SET.has(k) ? person : shared)[k] = v
  return { shared: shared as SharedSettings, person: person as PersonSettings }
}

const cleanName = (value: unknown): string =>
  typeof value === 'string' ? value.trim().slice(0, PERSON_NAME_MAX).trim() : ''

const cleanCompanyName = (value: unknown): string =>
  typeof value === 'string' ? value.trim().slice(0, COMPANY_NAME_MAX).trim() : ''

const cleanCompanyDayName = (value: unknown): string =>
  typeof value === 'string' ? value.trim().slice(0, COMPANY_DAY_NAME_MAX).trim() : ''

function updateCompany(state: PlannerState, id: string, change: (c: Company) => Company): PlannerState {
  if (!state.companies.some((c) => c.id === id)) return state
  return { ...state, companies: state.companies.map((c) => (c.id === id ? change(c) : c)) }
}

function updateActive(state: PlannerState, change: (p: Person) => Person): PlannerState {
  return { ...state, people: state.people.map((p) => (p.id === state.activePersonId ? change(p) : p)) }
}

function updatePerson(state: PlannerState, id: string, change: (p: Person) => Person): PlannerState {
  if (!state.people.some((p) => p.id === id)) return state
  return { ...state, people: state.people.map((p) => (p.id === id ? change(p) : p)) }
}

/** Click cycle for a bookable day: none → full → half → none. */
export function nextPortion(current: LeavePortion | undefined): LeavePortion | undefined {
  if (current === undefined) return 'full'
  if (current === 'full') return 'half'
  return undefined
}

export function plannerReducer(state: PlannerState, action: PlannerAction): PlannerState {
  switch (action.type) {
    case 'updateSettings': {
      const current = personSettings(state.shared, activePerson(state))
      const { shared, person } = splitSettings(sanitiseSettings({ ...current, ...action.patch }, current))
      return { ...updateActive(state, (p) => ({ ...p, ...person })), shared }
    }
    case 'cycleLeave':
      return updateActive(state, (p) => {
        const leave = { ...p.leave }
        const next = nextPortion(leave[action.date])
        if (next) leave[action.date] = next
        else delete leave[action.date]
        return { ...p, leave }
      })
    case 'setLeaveRange': {
      // Start/end may arrive in either order (drag or shift-click backwards).
      const [from, to] = action.start <= action.end ? [action.start, action.end] : [action.end, action.start]
      // The holiday index is derived from settings here rather than passed in, so
      // the action stays a plain serialisable value.
      const holidays = bankHolidayIndex(state.shared.region)
      const companyDays = companyIndexFor(state.companies, activePerson(state))
      return updateActive(state, (p) => {
        const settings = personSettings(state.shared, p)
        const leave = { ...p.leave }
        for (const date of eachDay(from, to)) {
          if (!isBookable(date, settings, holidays, companyDays)) continue
          if (action.portion) leave[date] = action.portion
          else delete leave[date]
        }
        return { ...p, leave }
      })
    }
    case 'clearLeaveInRange':
      return updateActive(state, (p) => ({
        ...p,
        leave: Object.fromEntries(Object.entries(p.leave).filter(([d]) => d < action.start || d > action.end)),
      }))
    case 'addPerson': {
      const name = cleanName(action.name)
      if (!name || state.people.some((p) => p.id === action.id)) return state
      const colour = isHexColour(action.colour)
        ? action.colour.toLowerCase()
        : nextPersonColour(state.people.map((p) => p.colour))
      const person: Person = { ...DEFAULT_PERSON_SETTINGS, id: action.id, name, colour, leave: {}, companyId: null }
      return { ...state, people: [...state.people, person], activePersonId: person.id, editingCompanyId: null }
    }
    case 'removePerson': {
      const index = state.people.findIndex((p) => p.id === action.id)
      if (index < 0 || state.people.length <= 1) return state
      const people = state.people.filter((p) => p.id !== action.id)
      const activePersonId =
        state.activePersonId === action.id ? people[Math.min(index, people.length - 1)].id : state.activePersonId
      return { ...state, people, activePersonId }
    }
    case 'renamePerson': {
      const name = cleanName(action.name)
      return name ? updatePerson(state, action.id, (p) => ({ ...p, name })) : state
    }
    case 'setPersonColour': {
      if (!isHexColour(action.colour)) return state
      const colour = action.colour.toLowerCase()
      return updatePerson(state, action.id, (p) => ({ ...p, colour }))
    }
    case 'selectPerson':
      return state.people.some((p) => p.id === action.id)
        ? { ...state, activePersonId: action.id, editingCompanyId: null }
        : state
    case 'addCompany': {
      const name = cleanCompanyName(action.name)
      if (!name || state.companies.length >= MAX_COMPANIES || state.companies.some((c) => c.id === action.id)) {
        return state
      }
      const active = activePerson(state)
      const adopt = companyOf(state.companies, active) === undefined
      return {
        ...state,
        companies: [...state.companies, { id: action.id, name, days: [] }],
        editingCompanyId: action.id,
        people: adopt
          ? state.people.map((p) => (p.id === active.id ? { ...p, companyId: action.id } : p))
          : state.people,
      }
    }
    case 'renameCompany': {
      const name = cleanCompanyName(action.name)
      return name ? updateCompany(state, action.id, (c) => ({ ...c, name })) : state
    }
    case 'removeCompany':
      if (!state.companies.some((c) => c.id === action.id)) return state
      return {
        ...state,
        companies: state.companies.filter((c) => c.id !== action.id),
        people: state.people.map((p) => (p.companyId === action.id ? { ...p, companyId: null } : p)),
        editingCompanyId: state.editingCompanyId === action.id ? null : state.editingCompanyId,
      }
    case 'selectCompany':
      return state.companies.some((c) => c.id === action.id) ? { ...state, editingCompanyId: action.id } : state
    case 'stopEditingCompany':
      return { ...state, editingCompanyId: null }
    case 'setPersonCompany':
      if (action.companyId !== null && !state.companies.some((c) => c.id === action.companyId)) return state
      return updatePerson(state, action.personId, (p) => ({ ...p, companyId: action.companyId }))
    case 'assignCompanyDays':
      return updateCompany(state, action.companyId, (company) => {
        const name = cleanCompanyDayName(action.name) || DEFAULT_COMPANY_DAY_NAME
        let days = company.days
        action.dates.forEach((date, i) => {
          if (!isIsoDate(date)) return
          const fields = { date, name, deducted: action.deducted === true, repeatsAnnually: action.repeatsAnnually === true }
          const existing = companyDayIndex(days).get(date)
          days = existing
            ? days.map((d) => (d.id === existing.id ? { ...fields, id: d.id } : d))
            : [...days, { ...fields, id: `${action.idPrefix}-${i}` }]
        })
        return { ...company, days: sanitiseCompanyDays(days) }
      })
    case 'removeCompanyDays':
      return updateCompany(state, action.companyId, (company) => {
        let days = company.days
        for (const date of action.dates) {
          if (!isIsoDate(date)) continue
          let match = companyDayIndex(days).get(date)
          while (match) {
            const id = match.id
            days = days.filter((d) => d.id !== id)
            match = companyDayIndex(days).get(date)
          }
        }
        return { ...company, days }
      })
    case 'removeCompanyDay':
      return updateCompany(state, action.companyId, (c) => ({ ...c, days: c.days.filter((d) => d.id !== action.id) }))
    case 'shiftYear':
      return { ...state, yearOffset: state.yearOffset + action.by }
    case 'resetYear':
      return { ...state, yearOffset: 0 }
    case 'replacePlan':
      return { ...action.plan, editingCompanyId: null, yearOffset: 0 }
  }
}

